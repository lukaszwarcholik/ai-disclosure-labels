/**
 * The flag lives on the ATTACHMENT, not on the post.
 *
 * An image marked once stays marked everywhere it is used - as a featured
 * image, inside content, in a gallery. If the flag lived on the post, the
 * same file used elsewhere would silently lose its label.
 */
define( 'AIDL_META', '_aidl_is_ai' );

/**
 * How the image was made: '' (not AI), 'generated' or 'modified'.
 *
 * The AI Act asks for a disclosure on both fully synthetic images and real
 * ones an AI has altered, but those are not the same claim and a reader can
 * tell the difference - so they get their own label. AIDL_META above stays
 * as the yes/no flag: it is what 1.0 wrote, what other code may already
 * read, and what the file-name map and the quick checks use.
 */
define( 'AIDL_META_MODE', '_aidl_mode' );
define( 'AIDL_OPTION', 'aidl_settings' );

