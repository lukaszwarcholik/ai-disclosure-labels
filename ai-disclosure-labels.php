/**
 * The modes an image can be in.
 *
 * @return array mode => label
 */
function aidl_modes() {

	return array(
		''          => __( 'Not AI', 'ai-disclosure-labels' ),
		'generated' => __( 'Generated by AI', 'ai-disclosure-labels' ),
		'modified'  => __( 'Modified using AI', 'ai-disclosure-labels' ),
	);
}

/**
 * How this image was made.
 *
 * Falls back to 'generated' for anything 1.0 marked before the modes
 * existed - an image that was flagged then was flagged as AI-made, and
 * silently unlabelling it on update would be the worst possible failure for
 * a plugin whose whole job is disclosure.
 *
 * @param int $attachment_id Attachment ID.
 * @return string '' , 'generated' or 'modified'
 */
function aidl_mode( $attachment_id ) {

	$attachment_id = (int) $attachment_id;
	$mode          = (string) get_post_meta( $attachment_id, AIDL_META_MODE, true );

	if ( isset( aidl_modes()[ $mode ] ) && '' !== $mode ) {
		return $mode;
	}

	return get_post_meta( $attachment_id, AIDL_META, true ) ? 'generated' : '';
}

/**
 * Is this attachment marked as AI in any way?
 *
 * @param int $attachment_id Attachment ID.
 * @return bool
 */
function aidl_is_ai( $attachment_id ) {
	return '' !== aidl_mode( $attachment_id );
}

/**
 * Write the mode, keeping the yes/no flag in step.
 *
 * @param int    $attachment_id Attachment ID.
 * @param string $mode          '', 'generated' or 'modified'.
 */
function aidl_set_mode( $attachment_id, $mode ) {

	$attachment_id = (int) $attachment_id;
	$mode          = isset( aidl_modes()[ $mode ] ) ? $mode : '';

	if ( '' === $mode ) {
		delete_post_meta( $attachment_id, AIDL_META_MODE );
		delete_post_meta( $attachment_id, AIDL_META );
		return;
	}

	update_post_meta( $attachment_id, AIDL_META_MODE, $mode );
	update_post_meta( $attachment_id, AIDL_META, 1 );
}

register_activation_hook( AIDL_FILE, 'aidl_activate' );
function aidl_activate() {

	if ( false === get_option( AIDL_OPTION ) ) {
		add_option( AIDL_OPTION, aidl_defaults() );
	}
}

/**
 * Settings link on the plugins list - small thing, but every reviewer
 * and every user looks for it there first.
 */
add_filter( 'plugin_action_links_' . plugin_basename( AIDL_FILE ), 'aidl_action_links' );
function aidl_action_links( $links ) {

	$link = '<a href="' . esc_url( admin_url( 'options-general.php?page=ai-disclosure-labels' ) ) . '">'
		. esc_html__( 'Settings', 'ai-disclosure-labels' ) . '</a>';

	array_unshift( $links, $link );

	return $links;
}
