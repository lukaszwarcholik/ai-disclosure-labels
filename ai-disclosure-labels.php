		'delete_data'  => 0,
	);
}

/**
 * One setting value, already merged with defaults.
 *
 * @param string $key Setting key.
 * @return mixed
 */
function aidl_get( $key ) {

	$zapisane = get_option( AIDL_OPTION, array() );
	$wszystkie = wp_parse_args( is_array( $zapisane ) ? $zapisane : array(), aidl_defaults() );

	return isset( $wszystkie[ $key ] ) ? $wszystkie[ $key ] : null;
}

